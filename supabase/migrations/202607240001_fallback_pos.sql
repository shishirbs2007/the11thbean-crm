from (values
  ('Bakes', 'Brownie', 'BRW', 100.00, 1),
  ('Bakes', 'Cake Pop', 'CKP', 60.00, 2),
  ('Bakes', 'Lemon Blueberry Cake', 'LBC', 90.00, 3),
  ('Bakes', 'Cookie', 'CKE', 70.00, 4),
  ('Bakes', 'Cupcake', 'CUP', 60.00, 5),
  ('Savoury', 'Roll', 'ROL', 90.00, 1),
  ('Savoury', 'Pizza Pocket', 'PZP', 90.00, 2)
) as v(category, name, sku, price, sort_order)
